"""Replay the complete M19 collection from exact CNF and original DRAT bytes.

This distribution needs no original LRAT files, no SAT search, no PySAT, and
no network. Each original CNF is regenerated byte-identically. Pinned DRAT-trim
reconstructs LRAT in private temporary storage, and pinned CakeML MUST accept
it against the same original CNF. Reconstructed LRATs are temporary; their
hashes and checker transcripts are retained. --quick never certifies all38.
"""
from pathlib import Path
from concurrent.futures import ProcessPoolExecutor, as_completed
from contextlib import ExitStack
import argparse, hashlib, importlib.util, json, os, re, shutil, tempfile, time

HERE=Path(__file__).resolve().parent
ROOT=HERE.parents[1]
IMPORT=ROOT/'research_round6/imported_claude_round4'
SOURCE_MANIFEST=ROOT/'research_round6/certification/M19_CERTIFICATE_MANIFEST.json'
MANIFEST=HERE/'COMPACT_M19_MANIFEST.json'

def module(name,path):
 spec=importlib.util.spec_from_file_location(name,path)
 result=importlib.util.module_from_spec(spec);spec.loader.exec_module(result);return result

A=module('compact_m19_original_audit',ROOT/'research_round5/proof_audit/audit_certificates.py')
E=module('compact_m19_exact_encoder',IMPORT/'src/encode_cnf2.py')
STORE=module('compact_m19_lossless_storage',HERE.parent/'certificate_storage.py')

def dump(path,value):
 path=Path(path);path.parent.mkdir(parents=True,exist_ok=True)
 with tempfile.NamedTemporaryFile(mode='w',encoding='utf-8',prefix='publish_',suffix='.json',dir=path.parent,delete=False) as handle:
  temporary=Path(handle.name);json.dump(value,handle,indent=2);handle.write('\n')
 try:os.replace(temporary,path)
 finally:temporary.unlink(missing_ok=True)

def load_and_bind():
 """Bind the full compact inventory to original hashes and exact marked cases.

 Only small manifests/source files are read here. Certificate bytes are checked
 and materialized independently for every case. No original LRAT is opened.
 """
 manifest=json.loads(MANIFEST.read_text())
 A.require(manifest['schema']=='kakeya-proof-audit-v1','Unexpected compact manifest schema')
 A.require(manifest['representation']=='ORIGINAL_CNF_AND_DRAT_ONLY','Unexpected representation')
 A.require(manifest['maximum_fibre']==19 and manifest['total_upper_bound']==93,'Wrong theorem parameters')
 A.require(A.sha(SOURCE_MANIFEST)==manifest['original_manifest_sha256'],'Original manifest changed')
 original=json.loads(SOURCE_MANIFEST.read_text())
 expected=manifest['expected_case_ids']
 A.require(isinstance(expected,list) and len(expected)==len(set(expected))==38,'Expected exactly38 distinct cases')
 original_cases={r['case_id']:r for r in original['cases']}
 A.require(set(expected)==set(original_cases) and len(original['cases'])==38,'Original case coverage differs')
 ids=[];cases=[]
 for saved in manifest['cases']:
  case=dict(saved);cid=case['case_id'];ids.append(cid)
  A.require(isinstance(cid,str) and re.fullmatch(r'[A-Za-z0-9][A-Za-z0-9_.-]*',cid),'Unsafe case identifier')
  A.require(cid in original_cases,'Unrecognized original case')
  old=original_cases[cid]
  A.require(case['marked_support']==old['marked_support'],'Marked support differs from original binding')
  A.require(case['metadata']==old['metadata'],'Input metadata differs from original binding')
  A.require(case.get('previously_accepted_lrat_sha256')==old['lrat_sha256'],'Original LRAT provenance hash differs')
  A.require(case['metadata']['m']==19 and case['metadata']['total_upper_bound']==93,'Wrong per-case parameters')
  for key in ('cnf','proof'):
   value=case[key];digest=case[key+'_sha256']
   A.require(isinstance(value,str) and not any(c in value for c in '\x00\r\n'),'Invalid certificate path')
   A.require(isinstance(digest,str) and re.fullmatch(r'[0-9a-f]{64}',digest),'A literal SHA256 is required')
   logical=(HERE/value).resolve()
   oldlogical=(SOURCE_MANIFEST.parent/old[key]).resolve()
   A.require(logical==oldlogical and digest==old[key+'_sha256'],'Original certificate binding differs')
   A.require(logical.is_file() or Path(str(logical)+'.xz').is_file(),'Missing original certificate representation')
   case[key+'_logical']=str(logical)
  cases.append(case)
 A.require(len(ids)==len(set(ids))==38 and set(ids)==set(expected),'Compact case inventory is not exactly complete')
 references=[]
 A.require(manifest['semantic_reference_files']==original['semantic_reference_files'],'Semantic-reference list differs')
 for reference in manifest['semantic_reference_files']:
  source=(HERE/reference['path']).resolve()
  A.require(source.is_file() and A.sha(source)==reference['sha256'],'Semantic source missing or changed')
  references.append(reference)
 contract=A.check_marked_contract(manifest,cases,MANIFEST)
 return manifest,cases,references,contract

def run_case(task):
 case,binaries,timeout,heap_mb,temporary_root=task
 cid=case['case_id'];logs=HERE/'replay_logs'/cid;logs.mkdir(parents=True,exist_ok=True)
 start=time.monotonic();result={'case_id':cid,'status':'RUNNING','marked_support':case['marked_support']}
 temporary_audit=None
 try:
  with tempfile.TemporaryDirectory(prefix=cid+'_',dir=temporary_root) as temp_name:
   temporary=Path(temp_name)
   try:
    support=case['marked_support']['support'];T=[x for x in support if x]
    A.require(case['marked_support']['distinguished_hub']==0,'Encoder requires hub zero')
    A.require(sum(1<<x for x in T)==case['metadata']['source_T_bitmask'],'Support metadata differs')
    SPEC=E.load_spectra(IMPORT/'data/spec32.csv');M=E.load_M(IMPORT/'data/Mtable.txt');SUBS=E.all_subspaces()
    f=E.encode(T,19,SPEC,M,SUBS);regenerated=temporary/'regenerated.cnf';E.write_dimacs(f,regenerated);del f
    A.require(A.sha(regenerated)==case['cnf_sha256'],'Exact CNF regeneration mismatch')
    with ExitStack() as stack:
     cnf=stack.enter_context(STORE.materialized(case['cnf_logical'],case['cnf_sha256'],temporary,prefer_compressed=True))
     drat=stack.enter_context(STORE.materialized(case['proof_logical'],case['proof_sha256'],temporary,prefer_compressed=True))
     temporary_audit=temporary/'audit'
     proof_result=A.check_pair(cnf,drat,temporary_audit,binaries,timeout,heap_mb,256,False)
     result.update(cnf_regeneration='BYTE_IDENTICAL',cnf_sha256=case['cnf_sha256'],original_drat_sha256=case['proof_sha256'],proof_check=proof_result)
     A.require(proof_result['input_sha256']=={'cnf':case['cnf_sha256'],'drat':case['proof_sha256']},'Checked inputs differ from declaration')
     A.require(proof_result['status']=='PASS_CNF_UNSAT_VIA_CAKEML_LRAT','Mandatory checker chain did not accept')
     for key in ('cnf','proof'):
      A.require(STORE.logical_sha(case[key+'_logical'],prefer_compressed=True)==case[key+'_sha256'],'Persisted input changed during checking')
     result.update(status='PASS_EXACT_CNF_DRAT_TO_CAKEML',original_lrat_required=False,original_lrat_read=False,reconstructed_lrat_sha256=proof_result['lrat_sha256'],reconstructed_lrat_bytes=proof_result['lrat_bytes'],reconstructed_lrat_retained=False)
   finally:
    if temporary_audit is not None and temporary_audit.exists():
     for log in temporary_audit.glob('*.txt'):
      shutil.copyfile(log,logs/log.name)
 except Exception as error:
  result.update(status='FAIL',error=repr(error))
 result['seconds']=round(time.monotonic()-start,6)
 dump(logs/'CASE_COMPACT_REPLAY.json',result)
 return result

def main():
 parser=argparse.ArgumentParser(description=__doc__)
 parser.add_argument('--jobs',type=int,choices=(1,2),default=1)
 parser.add_argument('--quick',action='store_true')
 parser.add_argument('--timeout',type=int,default=1800)
 parser.add_argument('--heap-mb',type=int,default=1024)
 args=parser.parse_args()
 A.require(args.timeout>0 and args.heap_mb>0,'Positive resource limits are required')
 receipt_path=HERE/('COMPACT_M19_QUICK_REPLAY.json' if args.quick else 'COMPACT_M19_REPLAY.json')
 receipt={'status':'RUNNING','quick':args.quick,'jobs':args.jobs,'cases':[],'original_lrat_required':False,'original_lrat_read':False}
 dump(receipt_path,receipt)
 start=time.monotonic()
 try:
  manifest,cases,references,contract=load_and_bind()
  pins=A.verify_sources()
  selected=cases
  if args.quick:
   selected=[next(c for c in cases if len(c['marked_support']['support'])==s) for s in (11,12)]
  # Larger original proofs first gives both workers useful work if jobs=2.
  source_receipts={r['case_id']:r for r in json.loads((ROOT/'research_round6/certification/M19_COMPLETE_CERTIFICATION_RECEIPT.json').read_text())['cases']}
  selected.sort(key=lambda c:source_receipts[c['case_id']]['drat_trim_seconds']+source_receipts[c['case_id']]['cake_lpr_seconds'],reverse=True)
  receipt.update(manifest_sha256=A.sha(MANIFEST),original_manifest_sha256=A.sha(SOURCE_MANIFEST),expected_case_ids=manifest['expected_case_ids'],requested_case_ids=[c['case_id'] for c in selected],marked_contract_check=contract,semantic_reference_hashes_checked=references,checker_pins=pins,encoder_soundness_proved_by_this_replay=False,acceptance='Exact original CNF regeneration and hashes; pinned DRAT-trim reconstructs LRAT; pinned CakeML must accept that LRAT against the same original CNF.',full_case_proof_coverage=False)
  with tempfile.TemporaryDirectory(prefix='kakeya_compact_m19_') as temporary:
   temp=Path(temporary);binaries,build=A.build_checkers(temp/'bin',HERE/'build_logs');receipt['checker_build']=build;dump(receipt_path,receipt)
   with ProcessPoolExecutor(args.jobs) as pool:
    futures=[pool.submit(run_case,(c,binaries,args.timeout,args.heap_mb,str(temp))) for c in selected]
    for future in as_completed(futures):
     item=future.result();receipt['cases'].append(item);receipt['seconds']=round(time.monotonic()-start,6);dump(receipt_path,receipt)
     print(f"[{len(receipt['cases'])}/{len(selected)}] {item['case_id']}: {item['status']} ({item['seconds']:.1f}s)",flush=True)
  A.require(len(receipt['cases'])==len(selected) and all(r['status']=='PASS_EXACT_CNF_DRAT_TO_CAKEML' for r in receipt['cases']),'One or more cases failed to certify')
  if not args.quick:
   A.require(len(receipt['cases'])==38 and {r['case_id'] for r in receipt['cases']}==set(manifest['expected_case_ids']),'Final proof coverage is incomplete')
  receipt.update(status='PASS_QUICK_TWO_CASES_ONLY' if args.quick else 'PASS_ALL_38_EXACT_CNF_DRAT_CAKEML_CERTIFICATES',checked_cases=len(receipt['cases']),full_case_proof_coverage=not args.quick,seconds=round(time.monotonic()-start,6))
  dump(receipt_path,receipt);print(receipt['status'],flush=True)
 except Exception as error:
  receipt.update(status='FAIL',error=repr(error),seconds=round(time.monotonic()-start,6));dump(receipt_path,receipt);raise

if __name__=='__main__':main()
