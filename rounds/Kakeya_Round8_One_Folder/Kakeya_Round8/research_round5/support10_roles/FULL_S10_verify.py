"""Independent role-first exhaustive verification of the full universe.

Partitions are counted by a bounded generating-function DP. Surviving
assignments are generated by first choosing three central weights and
then seven eligible ordinary weights. No producer is imported.
"""
from collections import defaultdict
from itertools import combinations_with_replacement,product
from pathlib import Path
import json
import sys
import time

HERE=Path(__file__).resolve().parent

def demand(w):
    c=w//2
    return 16//(1<<(c.bit_length()-1))

def partition_count(cap):
    dp={(0,0):1}
    for w in range(2,cap+1):
        new=defaultdict(int)
        for (n,total),count in dp.items():
            for k in range(min(10-n,(93-total)//w)+1):
                new[n+k,total+k*w]+=count
        dp=new
    return dp.get((10,93),0)

def resource():
    one=(0,0,1,2,4,5,7,9,12)
    # Verify the one-cube table by direct subset tuples, not bit masks.
    for k in range(9):
        from itertools import combinations
        best=max(sum((a^b) in {1,2,4} for a,b in combinations(points,2))
                 for points in combinations(range(8),k))
        assert best==one[k]
    out=[0]*33
    for split in product(range(9),repeat=4):
        n=sum(split);out[n]=max(out[n],sum(one[k] for k in split))
    return out

def ordinary_lists(eligible,n,total,prefix=()):
    if n==0:
        if total==0:yield prefix
        return
    if not eligible or total<n*eligible[0] or total>n*eligible[-1]:return
    for i,w in enumerate(eligible):
        yield from ordinary_lists(eligible[i:],n-1,total-w,prefix+(w,))

def enumerate_roles(E,use_cube):
    found=defaultdict(set);role_templates=0
    for c in combinations_with_replacement(range(2,19),3):
        ct=tuple(map(demand,c));cs=sum(ct)
        if any(max(ct[j] for j in range(3) if j!=i)>c[i]//2 for i in range(3)):continue
        budget=min(c[i]*c[i]//4-(cs-ct[i]) for i in range(3))
        eligible=[w for w in range(2,19)
                  if w//2>=max(ct) and (E[w] if use_cube else w*w//4)>=cs
                  and demand(w)<=min(x//2 for x in c)]
        if not eligible or 7*min(map(demand,eligible))>budget:continue
        for ordinary in ordinary_lists(eligible,7,93-sum(c)):
            if sum(map(demand,ordinary))>budget:continue
            role_templates+=1
            w=tuple(sorted(c+ordinary,reverse=True))
            found[w].add(tuple(sorted(c,reverse=True)))
    return dict(found),role_templates

def saved(name):
    return {tuple(r['weights']):{tuple(c) for c in r['allowed_central_triplets']}
            for r in json.loads((HERE/name).read_text())}

def main():
    assert not sys.flags.optimize
    start=time.monotonic();E=resource()
    count={m:partition_count(m)-partition_count(m-1) for m in range(10,19)}
    assert sum(count.values())==102842 and sum(v for m,v in count.items() if m>=12)==102620
    bare,nb=enumerate_roles(E,False);strong,ns=enumerate_roles(E,True)
    assert bare==saved('FULL_S10_BARE_ROLE_SURVIVORS.json') and len(bare)==174
    assert strong==saved('FULL_SUPPORT10_ROLE_SURVIVORS.json') and len(strong)==11
    producer=json.loads((HERE/'FULL_S10_PRODUCER_REPORT.json').read_text())
    assert {int(k):v for k,v in producer['by_maximum'].items()}==count
    assert producer['four_cube_edge_resources']==E
    surviving_rows=[{'weights':w,'central_triplets':sorted(strong[w])} for w in sorted(strong,reverse=True)]
    result={'status':'PASS_FULL_SUPPORT10_INDEPENDENT_REPLAY',
            'all_profiles':102842,'middle_profiles':102620,'low_maximum_profiles':222,
            'bare_role_survivors':174,'cube_role_survivors':11,
            'bare_role_templates':nb,'cube_role_templates':ns,
            'surviving_rows':surviving_rows,'by_maximum':count,
            'scope':'Independent generating-function count and role-first complete survivor enumeration. Eleven profiles remain for the separately proved rigidity stage; no prior screen is used.',
            'seconds':round(time.monotonic()-start,3)}
    (HERE/'FULL_SUPPORT10_ROLE_REPLAY.json').write_text(json.dumps(result,indent=2)+'\n')
    print(json.dumps(result,indent=2))

if __name__=='__main__':main()
