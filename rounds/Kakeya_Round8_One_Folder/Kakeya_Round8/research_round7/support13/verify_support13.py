import certify_support13 as P

HERE, ROOT, R6, A, C, E = P.HERE, P.ROOT, P.R6, P.A, P.C, P.E
MANIFEST = HERE/'SUPPORT13_CERTIFICATE_MANIFEST.json'
VARIANT_MODES = ('baseline','span','span4','dense','plane','combined')
GEOMETRY_MAP = HERE.parent/'geometry/SUPPORT13_MARKING_MAP.json'
INHERITED_FRONTIER = ROOT/'Kakeya_Research_Frontier_Round6.json'


def variant_module():
    return P.module('r7_s13_frozen_variant_replay',HERE.parent/'variant_trials.py')


def checked_unmarked_groups(catalogue):
    """Verify every displayed largest-vertex affine transport independently."""
    mapping=json.loads(GEOMETRY_MAP.read_text())
    A.require(mapping['marked_case_count']==55 and mapping['unmarked_affine_class_count']==13,
              'Unexpected geometric grouping size')
    targets={c['nonzero_support_mask']:set(c['support']) for c in catalogue}
    used=[];groups=mapping['groups']
    A.require(len(groups)==13 and len({g['unmarked_affine_orbit_id'] for g in groups})==13,
              'Duplicated unmarked group')
    for group in groups:
        source=group['representative_support'];transports=group['all_thirteen_hub_choices']
        A.require(len(source)==len(set(source))==13 and all(type(x)is int and 0<=x<32 for x in source),
                  'Malformed unmarked support representative')
        A.require(len(transports)==13 and {t['largest_vertex_in_representative'] for t in transports}==set(source),
                  'Some possible largest vertices lack transports')
        seen=[]
        for t in transports:
            hub=t['largest_vertex_in_representative'];cols=t['linear_columns_after_translation']
            A.require(len(cols)==5 and all(type(c)is int and 0<=c<32 for c in cols),'Invalid linear map')
            def linear(x):
                y=0
                for i,c in enumerate(cols):
                    if x>>i&1:y^=c
                return y
            A.require(len({linear(x) for x in range(32)})==32,'Singular affine transport')
            mask=t['target_marked_nonzero_mask'];seen.append(mask)
            A.require({linear(x^hub) for x in source}==targets.get(mask),'Affine support transport failed')
        masks=group['marked_nonzero_masks']
        A.require(len(masks)==len(set(masks))==group['marked_case_count'] and set(masks)==set(seen),
                  'Marked group differs from all possible hub choices')
        used+=masks
    A.require(len(used)==len(set(used))==55 and set(used)==set(targets),'Groups do not partition55marked cases')
    old=json.loads(INHERITED_FRONTIER.read_text())['dimension5_strata']['maximum11']
    remaining=old['remaining_orbits']
    A.require(len(remaining)==len(set(remaining))==old['remaining_affine_support_classes']==46,
              'Unexpected inherited maximum11 frontier')
    marked_open={g['unmarked_affine_orbit_id'] for g in groups
                 if g['exact_maximum11_still_open_in_inherited_frontier']}
    A.require(marked_open==set(remaining)&{g['unmarked_affine_orbit_id'] for g in groups}
              and len(marked_open)==old['remaining_counts_by_support']['13']==4,
              'Mapped maximum11 open classes differ from inherited ledger')
    return groups


def coverage(rows, catalogue):
    intervals = {c['nonzero_support_mask']: set() for c in catalogue}
    for row in rows:
        lower, upper = row['maximum_interval']
        intervals[row['nonzero_support_mask']].update(range(lower, upper+1))
    universe = set(range(2, 19))
    complete = sorted(mask for mask, values in intervals.items() if values == universe)
    partial = {str(mask): sorted(values) for mask, values in intervals.items()
               if values and values != universe}
    per_maximum = {str(m): sum(m in values for values in intervals.values()) for m in range(2,19)}
    closed_maxima = [m for m in range(2,19) if per_maximum[str(m)] == 55]
    groups=checked_unmarked_groups(catalogue)
    unmarked_by_m={str(m):[g['unmarked_affine_orbit_id'] for g in groups
                           if all(m in intervals[mask] for mask in g['marked_nonzero_masks'])]
                   for m in range(2,19)}
    unmarked_joint=[g['unmarked_affine_orbit_id'] for g in groups
                    if all(intervals[mask]==universe for mask in g['marked_nonzero_masks'])]
    m11_groups=[g for g in groups if g['exact_maximum11_still_open_in_inherited_frontier']]
    m11_newly_closed=[g['unmarked_affine_orbit_id'] for g in m11_groups
                      if all(11 in intervals[mask] for mask in g['marked_nonzero_masks'])]
    m11_remaining=[g['unmarked_affine_orbit_id'] for g in m11_groups
                    if g['unmarked_affine_orbit_id'] not in m11_newly_closed]
    m11_pending=sorted(mask for g in m11_groups for mask in g['marked_nonzero_masks']
                       if 11 not in intervals[mask])
    return {'complete_marked_cases': len(complete), 'complete_masks': complete,
            'partial_marked_cases': len(partial), 'partial_maxima_by_mask': partial,
            'remaining_without_complete_joint_coverage': 55-len(complete),
            'support13_closed_for_maximum2_through18': len(complete)==55,
            'certified_marked_cases_by_exact_maximum': per_maximum,
            'closed_support13_exact_maximum_cells': closed_maxima,
            'complete_unmarked_affine_classes_for_maximum2_through18': unmarked_joint,
            'complete_unmarked_affine_classes_by_exact_maximum': unmarked_by_m,
            'unmarked_accounting_includes_inherited_max11_class_exclusions': False,
            'separate_inherited_maximum11_slice':{
                'dependency':'Round6 maximum11 affine-class ledger; its exclusions are inherited, not new certificates.',
                'inherited_total_affine_classes':46,'inherited_support13_affine_classes':4,
                'inherited_support13_marked_roles':14,
                'newly_closed_previously_open_affine_classes':m11_newly_closed,
                'remaining_support13_affine_classes':m11_remaining,
                'remaining_total_maximum11_affine_class_count':46-len(m11_newly_closed),
                'remaining_support13_marked_roles':m11_pending,
                'support13_maximum11_closed_with_inherited_reduction':not m11_remaining,
                'middle_weight_profile_exclusions_from_this_slice':0},
            'band_coverage': {f'{lo}_{hi}': {
                'complete_marked_cases': sum(set(range(lo,hi+1)) <= values for values in intervals.values()),
                'remaining_masks': sorted(mask for mask, values in intervals.items()
                                           if not set(range(lo,hi+1)) <= values),
                'closed': all(set(range(lo,hi+1)) <= values for values in intervals.values())}
                for lo,hi in ((17,18),(15,16),(2,14),(18,18),(17,17))}}


def certificate_from_receipt(path):
    r = json.loads(path.read_text())
    if r['status'] != P.ACCEPTED:
        return None
    folder = path.parent
    row = {'case_id':r['case_id'], 'support':r['support'], 'distinguished_hub':0,
           'nonzero_support_mask':r['nonzero_support_mask'], 'maximum_interval':r['maximum_interval'],
           'total_upper_bound':r['total_upper_bound'], 'ring_scope':r['ring_scope'],
           'cnf':str((folder/'input.cnf').relative_to(ROOT)), 'cnf_sha256':r['cnf_sha256'],
           'proof':str((folder/'proof.drat').relative_to(ROOT)), 'proof_sha256':r['proof_sha256'],
           'proof_kind':'drat', 'receipt':str(path.relative_to(ROOT)), 'receipt_sha256':A.sha(path),
           'inherited':False}
    for key in ('cnf','proof'):
        logical = ROOT/row[key]
        A.require(C.logical_sha(logical, prefer_compressed=True)==row[key+'_sha256'],
                  'Certificate differs from completed production receipt')
        row[key+'_xz_sha256'] = A.sha(Path(str(logical)+'.xz'))
    A.require(r['semantic_input_hashes']==P.semantics(), 'Production semantic sources differ')
    prefix=folder/'rup_unit_prefix.txt';metadata=folder/'rup_unit_preprocessing.txt'
    if prefix.exists() or metadata.exists():
        A.require(prefix.is_file() and metadata.is_file(),'Incomplete preprocessing provenance')
        info=json.loads(metadata.read_text())
        A.require(info['original_cnf_sha256']==row['cnf_sha256']
                  and info['concatenated_drat_sha256']==row['proof_sha256'],
                  'Preprocessing provenance refers to different exact inputs')
        A.require(info['prefix_sha256']==A.sha(prefix),'Preprocessing prefix hash differs')
        expected=''.join(f'{u} 0\n' for u in info['added_units']).encode()
        A.require(prefix.read_bytes()==expected and len(info['added_units'])==info['added_unit_count'],
                  'Added unit list differs from exact DRAT prefix')
        with C.open_logical(ROOT/row['proof'],prefer_compressed=True) as stream:
            A.require(stream.read(len(expected))==expected,'Delivered original-CNF proof lacks declared prefix')
        row['search_preprocessing']={'kind':'UNTRUSTED_RUP_UNITS_WITH_ORIGINAL_CNF_PROOF',
             'prefix':str(prefix.relative_to(ROOT)),'prefix_sha256':A.sha(prefix),
             'metadata':str(metadata.relative_to(ROOT)),'metadata_sha256':A.sha(metadata),
             'added_unit_count':info['added_unit_count'],'preprocessor_trusted':False}
    return row


