#!/usr/bin/env python3
"""Fresh replay of a partial or complete support13 certificate collection.

The manifest is a frozen inventory, never an instruction to assume UNSAT.
Every requested CNF is regenerated byte-identically; every compressed proof
is hashed, materialized and checked. A full-support exclusion is reported
only when checked intervals cover2..18 for all55 catalogue representatives.
"""
from pathlib import Path
from contextlib import ExitStack
import argparse
import gc
